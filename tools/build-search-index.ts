/**
 * One-shot generator: merges the extracted page-content index JSON files into
 * `apps/web/lib/search-index.ts`.
 *
 * Run with: bun tools/build-search-index.ts
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const SOURCES_DIR = join(ROOT, 'tools/search-index-sources')

interface RawEntry {
  url: string
  title: string
  type: string
  category: string
  text: string
}
interface IndexEntry extends RawEntry {
  t: string
  k: string
}

function collectJsonFiles(dir: string): string[] {
  const out: string[] = []
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) out.push(...collectJsonFiles(full))
    else if (name.endsWith('.json')) out.push(full)
  }
  return out
}

const files = collectJsonFiles(SOURCES_DIR).sort()
const seen = new Set<string>()
const entries: IndexEntry[] = []

for (const file of files) {
  const rel = file.slice(SOURCES_DIR.length + 1).replace(/\\/g, '/')
  let parsed: RawEntry[]
  try {
    parsed = JSON.parse(readFileSync(file, 'utf8'))
  } catch (err) {
    console.error(`FAIL parse ${rel}: ${(err as Error).message}`)
    continue
  }
  let kept = 0
  for (const raw of parsed) {
    const url = String(raw.url || '').trim()
    const title = String(raw.title || '').trim()
    const text = String(raw.text || '').trim()
    if (!url || !title || text.length < 20) continue
    const searchable = `${title} ${text} ${raw.category ?? ''}`.toLowerCase()
    const key = `${url}|${title.toLowerCase()}`
    if (seen.has(key)) continue
    seen.add(key)
    entries.push({
      url,
      title,
      type: String(raw.type || 'page'),
      category: String(raw.category || 'Home'),
      text,
      t: searchable,
      k: `${title} ${raw.category ?? ''}`.toLowerCase(),
    })
    kept++
  }
  console.log(`${String(parsed.length).padStart(3)} read, ${String(kept).padStart(3)} kept  ${rel}`)
}

// Deterministic order: category, then page, then title.
const categoryOrder = [
  'Home', 'About', 'Academics', 'Preschool', 'Primary', 'Admissions',
  'Fees', 'Community', 'Contact', 'Legal',
]
entries.sort((a, b) => {
  const ca = categoryOrder.indexOf(a.category)
  const cb = categoryOrder.indexOf(b.category)
  if (ca !== cb) return (ca === -1 ? 99 : ca) - (cb === -1 ? 99 : cb)
  if (a.url !== b.url) return a.url.localeCompare(b.url)
  return a.title.localeCompare(b.title)
})

const header = `/*
 * Public-site search index — GENERATED by \`tools/build-search-index.ts\`.
 * Do not edit by hand. Re-run the generator after public page copy changes.
 *
 * Each entry carries the page's own visible text so search answers with the
 * words a visitor actually reads. \`t\` is the lower-cased searchable haystack
 * (title + text + category) and \`k\` the title haystack, precomputed once so
 * the search route does not rebuild them per request.
 */

export interface SearchIndexEntry {
  /** Page path the result navigates to. */
  url: string
  /** Short label for the result row. */
  title: string
  /** page | section | feature | program | subject | contact | policy | faq */
  type: string
  /** Nav grouping used for the result badge. */
  category: string
  /** The page's visible text, shown as the result snippet. */
  text: string
  /** Lower-cased haystack: title + text + category. */
  t: string
  /** Lower-cased title haystack. */
  k: string
}

export const SEARCH_INDEX: SearchIndexEntry[] = [
`

const body = entries
  .map(
    (e) =>
      `  { url: ${JSON.stringify(e.url)}, title: ${JSON.stringify(e.title)}, type: ${JSON.stringify(e.type)}, category: ${JSON.stringify(e.category)}, text: ${JSON.stringify(e.text)}, t: ${JSON.stringify(e.t)}, k: ${JSON.stringify(e.k)} },`,
  )
  .join('\n')

writeFileSync(
  join(ROOT, 'apps/web/lib/search-index.ts'),
  `${header}${body}\n]\n`,
  'utf8',
)
console.log(`\nWrote apps/web/lib/search-index.ts with ${entries.length} entries`)
